import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { migrationShapeProblems } from "./lib/validate-migration-shape.mjs";

const repoRoot = new URL("..", import.meta.url).pathname;
const catalogsRoot = join(repoRoot, "catalogs");
const output = join(repoRoot, "src", "generated", "bundled-catalogs.ts");
const uiOutput = join(repoRoot, "src", "generated", "bundled-catalog-ui.ts");

const catalogDirs = readdirSync(catalogsRoot)
  .map((name) => join(catalogsRoot, name))
  .filter((path) => {
    try {
      return statSync(join(path, "manifest.json")).isFile();
    } catch {
      return false;
    }
  })
  .sort();

// Per-catalog discovery: the manifest at <dir>/manifest.json plus any
// migration-vN-to-v(N+1).json files. Migration files travel with the
// catalog so the local-boot path can apply major-version upgrades to
// already-installed worlds without going through the GitHub tap.
let importIndex = 0;
let uiImportIndex = 0;
const importLines = [];
const entryLines = [];
const uiImportLines = [];
const uiEntryLines = [];
for (const dir of catalogDirs) {
  const manifestPath = join(dir, "manifest.json");
  const rawManifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const manifestVar = `manifest${importIndex++}`;
  importLines.push(
    `import ${manifestVar} from "${importPath(manifestPath)}";`
  );
  const migrationFiles = readdirSync(dir)
    .filter((name) => /^migration-v\d+-to-v\d+\.json$/.test(name))
    .sort();
  const migrationVars = [];
  const migrationPaths = [];
  for (const name of migrationFiles) {
    // Build-time shape gate: a malformed migration file (wrong keys, missing
    // steps) must fail HERE with the file named, not later as an
    // `undefined.split` inside the boot-upgrade picker. The runtime repeats
    // this check at module load (src/core/local-catalogs.ts) as defense in
    // depth; guard-catalog-migrations.mjs enforces it in `npm test` too.
    const migrationPath = join(dir, name);
    const fileFromRoot = relative(repoRoot, migrationPath).replaceAll("\\", "/");
    validateMigrationShape(fileFromRoot, JSON.parse(readFileSync(migrationPath, "utf8")));
    const v = `migration${importIndex++}`;
    importLines.push(
      `import ${v} from "${importPath(migrationPath)}";`
    );
    migrationVars.push(v);
    migrationPaths.push(fileFromRoot);
  }
  const fromRoot = relative(repoRoot, manifestPath).replaceAll("\\", "/");
  const migrationsExpr = migrationVars.length === 0
    ? "[]"
    : `[${migrationVars.map((v) => `${v} as unknown as CatalogMigrationManifest`).join(", ")}]`;
  entryLines.push(
    `  { path: ${JSON.stringify(fromRoot)}, manifest: ${manifestVar} as unknown as CatalogManifest, migrations: ${migrationsExpr}, migration_paths: ${JSON.stringify(migrationPaths)} }`
  );
  const uiModules = [];
  for (const module of rawManifest.ui?.modules ?? []) {
    if (typeof module?.id !== "string" || typeof module?.entry !== "string") continue;
    const moduleVar = `uiModule${uiImportIndex++}`;
    const uiModulePath = resolve(dir, module.entry);
    if (!uiModulePath.startsWith(`${resolve(dir)}${sep}`)) {
      throw new Error(`UI module ${rawManifest.name}:${module.id} escapes its catalog root`);
    }
    const uiImportPath = importPath(uiModulePath).replace(/\.(?:ts|tsx)$/, "");
    uiImportLines.push(`import * as ${moduleVar} from "${uiImportPath}";`);
    uiModules.push(`${JSON.stringify(module.id)}: ${moduleVar}`);
  }
  if (rawManifest.ui && uiModules.length > 0) {
    uiEntryLines.push(`  { alias: ${JSON.stringify(rawManifest.name)}, manifest: ${manifestVar}, modules: { ${uiModules.join(", ")} } }`);
  }
}

/** Shared shape contract: scripts/lib/validate-migration-shape.mjs. Failing
 * here (catalog:index) keeps a mis-shaped file out of the generated bundle
 * entirely; the guard and the runtime loader repeat the check. */
function validateMigrationShape(file, migration) {
  const problems = migrationShapeProblems(file, migration);
  if (problems.length > 0) {
    for (const problem of problems) console.error(`bundled catalog migration ${file}: ${problem}`);
    process.exit(1);
  }
}

function importPath(absPath) {
  const fromOutput = relative(join(repoRoot, "src", "generated"), absPath).replaceAll("\\", "/");
  return fromOutput.startsWith(".") ? fromOutput : `./${fromOutput}`;
}

mkdirSync(dirname(output), { recursive: true });

writeFileSync(output, `// Generated by scripts/generate-bundled-catalog-index.mjs.
// Do not hand-edit. Bundled catalogs are discovered from catalogs/*/manifest.json,
// and any migration-vN-to-v(N+1).json files in the catalog directory.

import type { CatalogManifest, CatalogMigrationManifest } from "../core/catalog-installer";
${importLines.join("\n")}

export type BundledCatalogEntry = {
  readonly path: string;
  readonly manifest: CatalogManifest;
  readonly migrations: readonly CatalogMigrationManifest[];
  /** Repo-relative source file of each migrations[i] — for load-time shape
   * errors that name the offending file. */
  readonly migration_paths: readonly string[];
};

export const BUNDLED_CATALOGS: readonly BundledCatalogEntry[] = [
${entryLines.join(",\n")}
];
`);

writeFileSync(uiOutput, `// Generated by scripts/generate-bundled-catalog-index.mjs.
// Do not hand-edit. This client-only index gives the bundler static module
// edges while discovery remains driven by each catalog manifest.

${importLines.filter((line) => line.includes("manifest")).join("\n")}
${uiImportLines.join("\n")}

export const BUNDLED_CATALOG_UI = [
${uiEntryLines.join(",\n")}
] as const;
`);
